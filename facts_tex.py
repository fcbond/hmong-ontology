#!/usr/bin/env python3
"""Write the figures in facts.json as LaTeX macros, for the paper to \\input.

Every number the paper cites comes from facts.json, which facts.py recomputes.
Typing those numbers into the paper by hand means every rebuild is followed by a
hunt through the text for the figures that changed, and some are always missed.
This writes them instead as one macro per figure, so the paper says
\\fact{coverage.everything.linked} and a rebuild updates it.

Keys are the facts.json paths joined with dots. Characters other than letters,
digits, dots and hyphens become hyphens, so "tiers.linked, stronger evidence" is
\\fact{tiers.linked-stronger-evidence}. Integers get thousands separators
(1,747); other numbers are written as they are (64.6). A key the paper uses but
the file lacks prints a bold ?? and a LaTeX warning, rather than failing quietly.

Usage:
    uv run facts_tex.py                          # facts.json -> facts.tex
    uv run facts_tex.py --out ../paper-hmong/facts.tex
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

HEADER = r"""% Generated by hmong-ontology/facts_tex.py from facts.json. Do not edit by hand:
% rerun facts.py and facts_tex.py instead. Use as \fact{coverage.everything.linked}.
\providecommand{\fact}[1]{%
  \ifcsname fact@#1\endcsname\csname fact@#1\endcsname
  \else\textbf{??}\PackageWarning{facts}{Undefined fact `#1'}\fi}
"""


def macro_key(path: str) -> str:
    """The macro key for a facts.json path: unsafe characters become hyphens."""
    return re.sub(r"-+", "-", re.sub(r"[^A-Za-z0-9.\-]", "-", path)).strip("-")


def format_value(value: int | float) -> str:
    """Thousands separators for integers; other numbers as written."""
    if isinstance(value, int):
        return f"{value:,}"
    return f"{value}"


def flatten(node: object, path: str = "") -> dict[str, int | float]:
    """Every numeric leaf of a facts.json tree, keyed by its dotted path."""
    if isinstance(node, dict):
        out: dict[str, int | float] = {}
        for key, value in node.items():
            out.update(flatten(value, f"{path}.{key}" if path else str(key)))
        return out
    if isinstance(node, (int, float)) and not isinstance(node, bool):
        return {path: node}
    return {}


def render(facts: dict) -> str:
    """The text of facts.tex."""
    lines = [HEADER]
    for path, value in sorted(flatten(facts).items()):
        lines.append(rf"\expandafter\def\csname fact@{macro_key(path)}\endcsname"
                     rf"{{{format_value(value)}}}")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--facts", type=Path, default=Path("facts.json"))
    parser.add_argument("--out", type=Path, default=Path("facts.tex"))
    args = parser.parse_args()
    facts = json.loads(args.facts.read_text(encoding="utf8"))
    args.out.write_text(render(facts), encoding="utf8")
    print(f"wrote {args.out}: {len(flatten(facts))} facts", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
